CREATE TABLE LOP
(
    MaLop VARCHAR(10) PRIMARY KEY,
    TenLop NVARCHAR(50) NOT NULL,
    SiSo INT
);
CREATE TABLE SINHVIEN
(
    MaSV VARCHAR(10) PRIMARY KEY,
    TenSV NVARCHAR(50) NOT NULL,
    NgaySinh DATE,
    GioiTinh NVARCHAR(10),
    MaLop VARCHAR(10),

    FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
);
